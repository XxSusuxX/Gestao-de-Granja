import fs from "node:fs";
import path from "node:path";

const distDir = path.resolve("artifacts/gestao-granja/dist/public");
const outFile = path.resolve("artifacts/api-server/src/generated-static.ts");

const assets = {};

function addFile(relPath, contentType) {
  const fullPath = path.join(distDir, relPath);
  if (fs.existsSync(fullPath)) {
    const content = fs.readFileSync(fullPath, "utf-8");
    assets[relPath.startsWith("/") ? relPath : `/${relPath}`] = {
      content,
      contentType,
    };
  }
}

if (fs.existsSync(distDir)) {
  addFile("index.html", "text/html; charset=utf-8");
  addFile("favicon.svg", "image/svg+xml");
  addFile("robots.txt", "text/plain; charset=utf-8");

  const assetsDir = path.join(distDir, "assets");
  if (fs.existsSync(assetsDir)) {
    for (const file of fs.readdirSync(assetsDir)) {
      if (file.endsWith(".css")) {
        addFile(`assets/${file}`, "text/css; charset=utf-8");
      } else if (file.endsWith(".js")) {
        addFile(`assets/${file}`, "application/javascript; charset=utf-8");
      }
    }
  }
}

const fileContent = `// Auto-generated by scripts/generate-static.mjs
export const staticAssets: Record<string, { content: string; contentType: string }> = ${JSON.stringify(assets, null, 2)};
`;

fs.writeFileSync(outFile, fileContent, "utf-8");
console.log(`Generated ${outFile} with ${Object.keys(assets).length} static assets.`);
